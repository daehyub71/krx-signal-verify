"""문구 규칙 — **도메인 층 · 순수 함수. 이 프로젝트의 가장 큰 리스크가 사는 곳이다.**

선행 `krx-signal-briefing`의 `render.py`에서 금지어 판정만 **떼어 이식**했다 (V11).
렌더링(HTML·평문)은 M5에서 새로 쓰지만, **무엇을 쓰면 안 되는가는 렌더보다 먼저 정해져야 한다** —
LLM 프롬프트·LLM 출력 검증·메일·웹 네 곳이 같은 규칙을 봐야 하기 때문이다 (N1).

## 왜 「합성어 먼저 지우기」가 필요한가

`순매도`는 수급을 말하는 유일한 말인데 `매도`를 품고 있다.
선행에서 이걸 놓쳐 **분석문 15개가 통째로 버려졌다** (2026-08-30 실호출).
그래서 검사 전에 허용 합성어를 지운다. 매매 판단(`매도 판단`·`매수 시점`)은 그대로 막힌다 —
**여기 적힌 형태만** 예외다.

## 원문은 검사하지 않는다

공시 제목·뉴스 제목은 남이 쓴 **원문**이라 금지어가 들어 있어도 그대로 싣는다.
`소송등의제기`·`불성실공시법인지정`이 그렇다. 검사는 **우리가 쓴 문장**에만 적용한다.
"""

from __future__ import annotations

# 우리가 쓰는 문장에 들어가면 안 되는 말 (N1).
#
# **경계는 「근거 정합성은 되고 매매 판단은 안 된다」이다** (선행 D24 계승).
# `호재`·`악재`는 금지어가 아니다 — 근거의 방향을 말하는 데 필요하고, 매매 판단은 아래가 막는다.
#
# **`RECIPIENTS` 본인 한 사람 유지가 전제다** (SPEC R1) — 남에게 보내면 판정문은 신고 대상이 된다.
FORBIDDEN: tuple[str, ...] = (
    "추천",
    "매수",
    "매도",
    "보류",
    "목표가",
    "손절",
    "여력",
    "이탈",
    "진입",
    "비중",
)

# 금지어 검사에서 **먼저 지우는** 합성어. 이 목록이 없으면 수급을 말할 수 없다.
ALLOWED_COMPOUNDS: tuple[str, ...] = ("순매수", "순매도", "매수세", "매도세", "매수관여율")


def has_forbidden(text: str) -> str:
    """우리 문장에 금지어가 있으면 **그 말을**, 없으면 빈 문자열 (N1).

    Args:
        text: 우리가 쓴 문장. 공시·뉴스 **원문은 넣지 않는다**.

    Returns:
        걸린 금지어 하나. 무엇이 걸렸는지 알아야 고칠 수 있으므로 bool이 아니라 말을 돌려준다.

    Note:
        `순매수`·`순매도` 같은 사실 표현은 **먼저 지우고** 검사한다.
    """
    rest = text
    for word in ALLOWED_COMPOUNDS:
        rest = rest.replace(word, " ")
    return next((w for w in FORBIDDEN if w in rest), "")
