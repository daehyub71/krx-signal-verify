"""문구 규칙 — **도메인 층 · 순수 함수. 이 프로젝트의 가장 큰 리스크가 사는 곳이다.**

선행 `krx-signal-briefing`의 `render.py`에서 금지어 판정만 **떼어 이식**했다 (V11).
렌더링(HTML·평문)은 M5에서 새로 쓰지만, **무엇을 쓰면 안 되는가는 렌더보다 먼저 정해져야 한다** —
LLM 프롬프트·LLM 출력 검증·메일·웹 네 곳이 같은 규칙을 봐야 하기 때문이다 (N1).

## 왜 「합성어 먼저 지우기」가 필요한가

`순매도`는 수급을 말하는 유일한 말인데 `매도`를 품고 있다.
선행에서 이걸 놓쳐 **분석문 15개가 통째로 버려졌다** (2026-08-30 실호출).
그래서 검사 전에 허용 합성어를 지운다. 매매 판단(`매도 판단`·`매수 시점`)은 그대로 막힌다 —
**여기 적힌 형태만** 예외다.

## 규칙이 둘이다

| | 막는 것 | 어디서 왔나 |
|---|---|---|
| **N1** | 매매 판단 (`매수`·`목표가`·`손절`…) | 선행에서 계승 |
| **N2** | 적중 문구 (`적중`·`승률`·`수익률`…) | **이 프로젝트에서 신설** |

N2는 이 프로젝트가 **판정을 저장하고 사후 주가를 붙이기 때문에** 생겼다.
「불일치 적중률 68%」 한 줄이면 다음 판정을 **예측으로 읽는다** (SPEC R2 — 최대 리스크).
문구로만 막지 않는다: `discriminate`의 반환 타입에 적중률 필드를 두지 않고,
`ksv_discrimination` 스키마에도 그런 열을 두지 않는다. **세 겹이다.**

## 원문은 검사하지 않는다

공시 제목·뉴스 제목은 남이 쓴 **원문**이라 금지어가 들어 있어도 그대로 싣는다.
`소송등의제기`·`불성실공시법인지정`이 그렇다. 검사는 **우리가 쓴 문장**에만 적용한다.
"""

from __future__ import annotations

# 우리가 쓰는 문장에 들어가면 안 되는 말 (N1).
#
# **경계는 「근거 정합성은 되고 매매 판단은 안 된다」이다** (선행 D24 계승).
# `호재`·`악재`는 금지어가 아니다 — 근거의 방향을 말하는 데 필요하고, 매매 판단은 아래가 막는다.
#
# **`RECIPIENTS` 본인 한 사람 유지가 전제다** (SPEC R1) — 남에게 보내면 판정문은 신고 대상이 된다.
FORBIDDEN: tuple[str, ...] = (
    "추천",
    "매수",
    "매도",
    "보류",
    "목표가",
    "손절",
    "여력",
    "이탈",
    "진입",
    "비중",
)

# 금지어 검사에서 **먼저 지우는** 합성어. 이 목록이 없으면 수급도 공매도도 말할 수 없다.
#
# **`공매도`가 `매도`에 걸린다** — 선행에는 공매도 갈래가 없어 이 말이 목록에 없었다.
# `공매도 비중`은 `비중`에도 걸린다. F32가 요구하는 「거래량·비중(%)」을 못 쓰게 되는 셈이다
# (2026-09-05, F34 작업 중 테스트가 잡았다).
#
# **긴 것부터 지운다** — `공매도`를 먼저 지우면 `비중`이 남아 걸린다.
# 순서를 사람이 지키게 두지 않고 `has_forbidden`이 길이순으로 정렬한다.
ALLOWED_COMPOUNDS: tuple[str, ...] = (
    "공매도 비중",
    "공매도비중",
    "공매도",
    "순매수",
    "순매도",
    "매수세",
    "매도세",
    "매수관여율",
)


def has_forbidden(text: str) -> str:
    """우리 문장에 금지어가 있으면 **그 말을**, 없으면 빈 문자열 (N1).

    Args:
        text: 우리가 쓴 문장. 공시·뉴스 **원문은 넣지 않는다**.

    Returns:
        걸린 금지어 하나. 무엇이 걸렸는지 알아야 고칠 수 있으므로 bool이 아니라 말을 돌려준다.

    Note:
        `순매수`·`공매도 비중` 같은 사실 표현은 **먼저 지우고** 검사한다. 긴 것부터 지운다.
    """
    rest = text
    # **긴 것부터.** `공매도`를 `공매도 비중`보다 먼저 지우면 `비중`이 남아 걸린다.
    for word in sorted(ALLOWED_COMPOUNDS, key=len, reverse=True):
        rest = rest.replace(word, " ")
    return next((w for w in FORBIDDEN if w in rest), "")


# ── N2 적중 문구 (이 프로젝트에서 신설) ─────────────────────────
#
# **「불일치」는 "근거가 신호와 어긋난다"이지 "떨어진다"가 아니다.**
# 개별 종목에 「맞았다/틀렸다」를 매기는 순간, 이 프로젝트는 하지 않기로 한 일(예측)을 한다.
#
# `예측`은 **금지하지 않는다** — 한계 문구가 「예측이 아니다」라고 말해야 하기 때문이다.
# 막는 것은 성과를 주장하는 말이다.
FORBIDDEN_OUTCOME: tuple[str, ...] = (
    "적중",
    "승률",
    "수익률",
    "정확도",
    "맞혔",
    "맞았",
    "틀렸",
    "빗나",
)

# 우리가 써야 하는 말. `초과수익`은 관측치의 이름이라 `수익률`에 걸리면 안 된다.
ALLOWED_OUTCOME_COMPOUNDS: tuple[str, ...] = ("초과수익",)

# 대신 쓰는 말 — 오류 메시지에 실어 고칠 방향을 알려 준다.
OUTCOME_ALTERNATIVES = "초과수익 분포 · 분별력 · 표본 수"


def has_forbidden_outcome(text: str) -> str:
    """적중 문구가 있으면 **그 말을**, 없으면 빈 문자열 (N2).

    Args:
        text: 우리가 쓴 문장.

    Returns:
        걸린 말 하나. 고칠 방향은 `OUTCOME_ALTERNATIVES`에 있다.
    """
    rest = text
    for word in ALLOWED_OUTCOME_COMPOUNDS:
        rest = rest.replace(word, " ")
    return next((w for w in FORBIDDEN_OUTCOME if w in rest), "")


def first_violation(text: str) -> tuple[str, str]:
    """두 규칙을 한 번에 본다.

    Returns:
        `("N1", 걸린말)` · `("N2", 걸린말)` · `("", "")`. **어느 규칙인지까지 돌려준다** —
        고치는 방향이 다르기 때문이다(N1은 사실로, N2는 분포·표본 수로).
    """
    if (w := has_forbidden(text)):
        return "N1", w
    if (w := has_forbidden_outcome(text)):
        return "N2", w
    return "", ""
